from __future__ import annotations


def deterministic_originalize_i2i_fallback_prompt(prompt_text: str, reference_hint: str) -> str:
    hint = reference_hint or "上传参考图"
    return "\n".join(
        [
            f"意图：参考“{hint}”的高层灵感，围绕“{prompt_text}”重新设计一个原创可用资产，降低可识别 IP 相似度。",
            "角色/主体：只保留宽泛类别、功能定位、气质和材质方向；重新设计身份、脸部/头部细节、轮廓比例、服饰/外壳系统和标志性辨识点。",
            "场景/美术：可借鉴整体氛围、材质情绪和色彩关系，但不复制原图独特场景、logo、文字、图案、经典构图或 franchise 视觉符号。",
            f"动作/情节：执行“{prompt_text}”这个新目标；动作和情境服务新设计，不沿用参考图经典姿势、名场面或固定剧情关系。",
            "镜头/构图：重新组织景别、角度、主体位置和画面布局，避免贴近参考图的姿势、剪影、四视图排列或标志性构图。",
            "灯光：保持主体清楚可读，重新设计光源方向、明暗层次和材质反射，不形成原图复刻感。",
            "运动/时间推进：单帧以新资产状态可读为主；若后续接视频，保留原创结构和自然动作余量。",
            "连续性：新资产内部身份、材质、比例和色彩要自洽；参考图只作为灵感证据，不作为身份、服装、比例、构图或未修改细节锁定项。",
            "负面约束：不要复制已知角色、商标、logo、标志性服装、武器、姿势、构图或可识别 IP 组合；不要水印、文字乱码、畸形肢体或身份漂移。",
        ]
    )


__all__ = ("deterministic_originalize_i2i_fallback_prompt",)
